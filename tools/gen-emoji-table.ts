// Generates src/core/emoji-table.json, the hub's reaction vocabulary (spec
// 5.6), from Unicode's emoji-test.txt. Run by hand when the pinned version
// changes, and commit the output:
//
//   node tools/gen-emoji-table.ts path/to/emoji-test.txt
//
// The input must match PINNED_SHA256. The hub never reads emoji-test.txt and
// never derives a name at runtime: it reads only the committed table.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const PINNED_VERSION = '16.0';
export const PINNED_SHA256 = '24f0c534e86cf142e2496953e8f0e46a3e702392911eddcd29c6cced85139697';
const SOURCE_URL = `https://www.unicode.org/Public/emoji/${PINNED_VERSION}/emoji-test.txt`;

/** Emoji that read as sign-off, left out of the table so they fail as
 * invalid_reaction. Matched on the CLDR name, skin-tone variants included. */
export const SIGN_OFF_NAMES = [
  'check mark button',
  'check mark',
  'check box with check',
  'OK hand',
  'OK button',
  'rocket',
  'hundred points',
  'locked with pen',
];

const SLUG = /^[a-z0-9_]{1,64}$/;

export function slugFor(name: string): string {
  return name
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .replace(/&/g, ' and ')
    .replace(/#/g, ' number sign ')
    .replace(/\*/g, ' asterisk ')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
}

function isSignOff(name: string): boolean {
  return SIGN_OFF_NAMES.some((s) => name === s || name.startsWith(`${s}: `));
}

/** Unicode tag characters, which build subdivision flags and are the same
 * hidden characters the escaping strips. */
function hasTagCharacter(s: string): boolean {
  return [...s].some((c) => {
    const cp = c.codePointAt(0)!;
    return cp >= 0xe0000 && cp <= 0xe007f;
  });
}

export interface TableEntry {
  /** The fully-qualified emoji. */
  e: string;
  /** The delivered name. */
  n: string;
  /** Minimally-qualified and unqualified forms that match this entry. */
  a?: string[];
}

export function buildTable(text: string): { entries: TableEntry[]; dropped: string[] } {
  const byName = new Map<string, TableEntry>();
  const order: TableEntry[] = [];
  const dropped: string[] = [];
  const excluded = new Set<string>();
  for (const line of text.split('\n')) {
    const m = /^([0-9A-F ]+?)\s*;\s*(fully-qualified|minimally-qualified|unqualified|component)\s*#\s*(\S+)\s+E\d+\.\d+\s+(.+)$/.exec(line);
    if (!m) continue;
    const [, cps, status, , name] = m as unknown as [string, string, string, string, string];
    const emoji = String.fromCodePoint(...cps.split(' ').map((h) => parseInt(h, 16)));
    if (status === 'component') continue;
    if (status === 'fully-qualified') {
      if (isSignOff(name) || hasTagCharacter(emoji)) {
        excluded.add(name);
        continue;
      }
      const slug = slugFor(name);
      if (!SLUG.test(slug)) {
        dropped.push(name);
        excluded.add(name);
        continue;
      }
      const entry: TableEntry = { e: emoji, n: slug };
      byName.set(name, entry);
      order.push(entry);
    } else {
      if (excluded.has(name)) continue;
      const entry = byName.get(name);
      if (!entry) throw new Error(`no fully-qualified entry before ${status} form of ${name}`);
      (entry.a ??= []).push(emoji);
    }
  }
  // Names and forms must be unique across the whole table, and `none` is
  // reserved for clearing a reaction.
  const seen = new Set<string>(['none']);
  for (const entry of order) {
    for (const key of [entry.n, entry.e, ...(entry.a ?? [])]) {
      if (seen.has(key)) throw new Error(`duplicate table key ${JSON.stringify(key)}`);
      seen.add(key);
    }
  }
  return { entries: order, dropped };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const input = process.argv[2];
  if (!input) throw new Error('usage: node tools/gen-emoji-table.ts path/to/emoji-test.txt');
  const raw = readFileSync(input);
  const sha = createHash('sha256').update(raw).digest('hex');
  if (sha !== PINNED_SHA256) throw new Error(`emoji-test.txt sha256 ${sha} does not match the pinned ${PINNED_SHA256}`);
  const { entries, dropped } = buildTable(raw.toString('utf8'));
  const out = {
    notice: `Generated by tools/gen-emoji-table.ts from Unicode emoji-test.txt ${PINNED_VERSION} (${SOURCE_URL}, sha256 ${PINNED_SHA256}). Do not edit by hand. Emoji data copyright Unicode, Inc., used under the Unicode License v3 (https://www.unicode.org/license.txt).`,
    version: PINNED_VERSION,
    sign_off_excluded: SIGN_OFF_NAMES,
    entries,
  };
  const target = fileURLToPath(new URL('../src/core/emoji-table.json', import.meta.url));
  writeFileSync(target, JSON.stringify(out, null, 0).replace(/\},\{/g, '},\n{') + '\n');
  console.log(`${entries.length} entries written; ${dropped.length} left out because their name would pass 64 characters`);
}
